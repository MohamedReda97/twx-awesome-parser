/**
 * BusinessObjectGenerator - Transforms parsed object definitions into IBM BPM Business Object structure
 * Generates unique IDs, sanitizes names, and creates proper business object metadata
 */

const { v4: uuidv4 } = require('crypto')

class BusinessObjectGenerator {
  constructor() {
    this.generatedIds = new Set() // Track generated IDs to ensure uniqueness
  }

  /**
   * Generate business object from parsed definition
   * @param {Object} objectDefinition - Parsed object definition from SimpleJSONParser
   * @returns {Object} IBM BPM business object structure
   */
  generateBusinessObject(objectDefinition) {
    if (!objectDefinition) {
      throw new Error('Object definition is required')
    }

    // Handle both 'name' and 'objectName' properties for flexibility
    const objectName = objectDefinition.name || objectDefinition.objectName
    if (!objectName) {
      throw new Error('Object definition must have a name or objectName')
    }

    const sanitizedName = this.sanitizeName(objectName)
    const objectId = this.generateObjectId()
    const versionId = this.generateVersionId()
    const timestamp = new Date().toISOString()

    return {
      id: objectId,
      versionId: versionId,
      name: sanitizedName,
      originalName: objectName,
      properties: this.createProperties(objectDefinition.properties || []),
      metadata: {
        createdAt: timestamp,
        createdBy: 'BusinessObjectBuilder',
        lastModified: timestamp,
        lastModifiedBy: 'BusinessObjectBuilder',
        type: 'twClass',
        subType: 'BusinessObject',
        isSystem: false,
        shared: false,
        isShadow: false,
        globalLifetime: false
      },
      externalId: `itm.${objectId}`,
      guid: this.generateGUID(),
      description: `Business object ${sanitizedName} generated by Business Object Builder`
    }
  }

  /**
   * Create properties from definition
   * @param {Array} properties - Array of property definitions
   * @returns {Array} Array of IBM BPM property structures
   */
  createProperties(properties) {
    if (!Array.isArray(properties)) {
      return []
    }

    return properties.map((prop, index) => {
      if (!prop.name || !prop.type) {
        throw new Error(`Property at index ${index} must have name and type`)
      }

      return {
        name: this.sanitizeName(prop.name),
        originalName: prop.name,
        bpmType: prop.type, // This will be mapped by TypeMapper later
        isRequired: prop.isRequired || false,
        isHidden: prop.isHidden || false,
        isArray: prop.isArray || false,
        description: prop.description || `Property ${prop.name}`,
        defaultValue: prop.defaultValue || null,
        constraints: prop.constraints || {},
        metadata: {
          order: index,
          createdAt: new Date().toISOString(),
          createdBy: 'BusinessObjectBuilder'
        }
      }
    })
  }

  /**
   * Generate unique object ID in IBM BPM format (12.xxx)
   * @returns {string} Unique object ID
   */
  generateObjectId() {
    let id
    let attempts = 0
    const maxAttempts = 100

    do {
      // Generate UUID and format for IBM BPM
      const uuid = this.generateUUID()
      id = `12.${uuid}`
      attempts++
      
      if (attempts > maxAttempts) {
        throw new Error('Unable to generate unique object ID after maximum attempts')
      }
    } while (this.generatedIds.has(id))

    this.generatedIds.add(id)
    return id
  }

  /**
   * Generate version ID (UUID format)
   * @returns {string} Version ID
   */
  generateVersionId() {
    return this.generateUUID()
  }

  /**
   * Generate GUID for business object
   * @returns {string} GUID
   */
  generateGUID() {
    return this.generateUUID()
  }

  /**
   * Generate UUID
   * @returns {string} UUID string
   */
  generateUUID() {
    // Generate UUID v4 manually since crypto.randomUUID might not be available in all Node versions
    return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, function(c) {
      const r = Math.random() * 16 | 0
      const v = c === 'x' ? r : (r & 0x3 | 0x8)
      return v.toString(16)
    })
  }

  /**
   * Apply IBM BPM naming conventions
   * @param {string} name - Original name
   * @returns {string} Sanitized name
   */
  sanitizeName(name) {
    if (!name || typeof name !== 'string') {
      throw new Error('Name must be a non-empty string')
    }

    let sanitized = name.trim()

    // Remove invalid characters and replace with underscores
    sanitized = sanitized.replace(/[^a-zA-Z0-9_]/g, '_')

    // Ensure it starts with a letter or underscore
    if (!/^[a-zA-Z_]/.test(sanitized)) {
      sanitized = '_' + sanitized
    }

    // Remove consecutive underscores
    sanitized = sanitized.replace(/_+/g, '_')

    // Remove trailing underscores
    sanitized = sanitized.replace(/_+$/, '')

    // Ensure minimum length
    if (sanitized.length === 0) {
      sanitized = 'BusinessObject'
    }

    // Ensure maximum length (IBM BPM typically has limits)
    if (sanitized.length > 64) {
      sanitized = sanitized.substring(0, 64)
    }

    // Handle reserved words
    const reservedWords = [
      'class', 'interface', 'abstract', 'extends', 'implements',
      'public', 'private', 'protected', 'static', 'final',
      'void', 'return', 'if', 'else', 'for', 'while', 'do',
      'switch', 'case', 'default', 'break', 'continue',
      'try', 'catch', 'finally', 'throw', 'throws',
      'new', 'this', 'super', 'null', 'true', 'false'
    ]

    if (reservedWords.includes(sanitized.toLowerCase())) {
      sanitized = sanitized + '_BO'
    }

    return sanitized
  }

  /**
   * Validate business object structure
   * @param {Object} businessObject - Business object to validate
   * @returns {Object} Validation result
   */
  validateBusinessObject(businessObject) {
    const result = {
      isValid: true,
      errors: [],
      warnings: []
    }

    // Required fields validation
    const requiredFields = ['id', 'versionId', 'name', 'properties', 'metadata']
    for (const field of requiredFields) {
      if (!businessObject[field]) {
        result.errors.push(`Missing required field: ${field}`)
        result.isValid = false
      }
    }

    // ID format validation
    if (businessObject.id && !businessObject.id.match(/^12\.[a-f0-9-]{36}$/)) {
      result.errors.push('Invalid ID format. Expected: 12.xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx')
      result.isValid = false
    }

    // Version ID format validation
    if (businessObject.versionId && !businessObject.versionId.match(/^[a-f0-9-]{36}$/)) {
      result.errors.push('Invalid version ID format. Expected UUID format')
      result.isValid = false
    }

    // Name validation
    if (businessObject.name && !businessObject.name.match(/^[a-zA-Z_][a-zA-Z0-9_]*$/)) {
      result.errors.push('Invalid name format. Must start with letter or underscore, contain only alphanumeric characters and underscores')
      result.isValid = false
    }

    // Properties validation
    if (businessObject.properties && Array.isArray(businessObject.properties)) {
      businessObject.properties.forEach((prop, index) => {
        if (!prop.name) {
          result.errors.push(`Property at index ${index} missing name`)
          result.isValid = false
        }
        if (!prop.bpmType) {
          result.errors.push(`Property ${prop.name || index} missing bpmType`)
          result.isValid = false
        }
      })
    }

    // Warnings for best practices
    if (businessObject.properties && businessObject.properties.length === 0) {
      result.warnings.push('Business object has no properties')
    }

    if (businessObject.name && businessObject.name.length > 32) {
      result.warnings.push('Business object name is quite long, consider shortening for better readability')
    }

    return result
  }

  /**
   * Generate multiple business objects from array of definitions
   * @param {Array} objectDefinitions - Array of object definitions
   * @returns {Array} Array of generated business objects
   */
  generateMultipleBusinessObjects(objectDefinitions) {
    if (!Array.isArray(objectDefinitions)) {
      throw new Error('Object definitions must be an array')
    }

    const results = []
    const errors = []

    for (let i = 0; i < objectDefinitions.length; i++) {
      try {
        const businessObject = this.generateBusinessObject(objectDefinitions[i])
        results.push(businessObject)
      } catch (error) {
        errors.push({
          index: i,
          definition: objectDefinitions[i],
          error: error.message
        })
      }
    }

    return {
      businessObjects: results,
      errors: errors,
      summary: {
        total: objectDefinitions.length,
        successful: results.length,
        failed: errors.length
      }
    }
  }

  /**
   * Get generation statistics
   * @returns {Object} Statistics about generated objects
   */
  getStatistics() {
    return {
      totalGenerated: this.generatedIds.size,
      generatedIds: Array.from(this.generatedIds)
    }
  }

  /**
   * Reset generator state
   */
  reset() {
    this.generatedIds.clear()
  }

  /**
   * Create a business object template
   * @param {string} name - Object name
   * @returns {Object} Template object definition
   */
  createTemplate(name) {
    return {
      name: name || 'NewBusinessObject',
      properties: [
        {
          name: 'id',
          type: 'string',
          description: 'Unique identifier'
        },
        {
          name: 'name',
          type: 'string',
          description: 'Display name'
        },
        {
          name: 'createdDate',
          type: 'Date',
          description: 'Creation timestamp'
        },
        {
          name: 'isActive',
          type: 'Boolean',
          description: 'Active status flag'
        }
      ]
    }
  }
}

module.exports = BusinessObjectGenerator